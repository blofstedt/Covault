#!/usr/bin/env node
/**
 * Turn the sideload manifest into the one Google Play will accept.
 *
 * Covault is distributed two ways and they want opposite things of the
 * manifest. A sideloaded APK updates itself and discovers banking apps by
 * looking at what is installed; Play forbids both — an app that installs
 * packages, and one that can see every package on the phone, are each a policy
 * violation on their own.
 *
 * So this strips five permissions and replaces the blunt one with an explicit
 * <queries> list of the banking and mail apps Covault already knows by name.
 *
 * What that costs, plainly: on a Play install the capture-sources screen can
 * only offer banks that are on the list, and the "we noticed an app that looks
 * like a bank" suggestion cannot happen at all. Capture itself is unaffected —
 * a notification listener receives notifications from every app regardless of
 * package visibility, so a bank Covault has never heard of is still captured
 * once the user approves it some other way.
 *
 * The self-updater needs nothing here: the app already hands updates off to
 * the Play Store when it can see it was installed from there (see
 * lib/covaultUpdater.ts and playStoreUpdateRoute.test.ts), so without the
 * install permissions that path is simply never taken.
 *
 * Run as a filter — reads the sideload manifest, writes the Play one — so the
 * default build path never goes anywhere near it. playManifest.test.ts runs
 * this against the real manifest.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

/**
 * The permissions Play will not take, and why each is in the sideload build.
 *
 * Removing one that is load-bearing for capture would be a silent disaster, so
 * this list is exactly the five the manifest itself already flags as
 * Play-hostile — nothing about notifications, foreground services or boot
 * receipt is touched.
 */
export const PLAY_FORBIDDEN_PERMISSIONS = [
  // Seeing every installed package. Replaced by <queries> below.
  'android.permission.QUERY_ALL_PACKAGES',
  // Installing an APK, and doing it without a confirmation dialog. Both exist
  // for the self-updater, which a Play build does not use.
  'android.permission.REQUEST_INSTALL_PACKAGES',
  'android.permission.UPDATE_PACKAGES_WITHOUT_USER_ACTION',
  // Downloading that update without putting it in the shade.
  'android.permission.DOWNLOAD_WITHOUT_NOTIFICATION',
  // Asking to be exempt from battery optimisation. The app already falls back
  // to sending the user to Android's own settings screen, which is what the
  // Play build does instead.
  'android.permission.REQUEST_IGNORE_BATTERY_OPTIMIZATIONS',
];

/** Mail apps Covault reads bank email from. Mirrors lib/emailNotification.ts. */
const MAIL_PACKAGES = [
  'com.google.android.gm',
  'com.microsoft.office.outlook',
  'com.yahoo.mobile.client.android.mail',
  'com.samsung.android.email.provider',
  'ch.protonmail.android',
  'com.fsck.k9',
  'org.kman.AquaMail',
];

/** Every banking package the app knows, read from its own list. */
export function bankingPackages() {
  const source = readFileSync(resolve(ROOT, 'lib/bankingApps.ts'), 'utf8');
  const start = source.indexOf('export const KNOWN_BANKING_APPS');
  if (start < 0) throw new Error('KNOWN_BANKING_APPS not found in lib/bankingApps.ts');
  const end = source.indexOf('\n};', start);
  const body = source.slice(start, end);
  const found = [...body.matchAll(/^\s*'([a-zA-Z0-9._]+)'\s*:/gm)].map((m) => m[1]);
  return [...new Set(found)].sort();
}

/** The <queries> block that replaces QUERY_ALL_PACKAGES. */
export function queriesBlock(packages) {
  const lines = packages.map((p) => `        <package android:name="${p}" />`);
  return [
    '    <!--',
    '      Generated by scripts/play-manifest.mjs from lib/bankingApps.ts. Do not',
    '      edit here.',
    '',
    '      The Play build cannot ask which packages are installed, so it names',
    '      the ones it cares about. A bank missing from this list is NOT a bank',
    '      Covault fails to capture — a notification listener hears every app —',
    '      it is one the capture-sources screen cannot show as installed.',
    '    -->',
    '    <queries>',
    ...lines,
    '    </queries>',
  ].join('\n');
}

/**
 * Strip the forbidden permissions, carrying their explanatory comments with
 * them, and put the <queries> block where QUERY_ALL_PACKAGES was.
 */
export function toPlayManifest(xml) {
  let out = xml;
  const missing = [];

  for (const permission of PLAY_FORBIDDEN_PERMISSIONS) {
    const line = new RegExp(
      `[ \\t]*<uses-permission android:name="${permission.replace(/\./g, '\\.')}"[^>]*/>\\n`,
    );
    if (!line.test(out)) {
      missing.push(permission);
      continue;
    }
    const replacement = permission === 'android.permission.QUERY_ALL_PACKAGES'
      ? `${queriesBlock(bankingPackages().concat(MAIL_PACKAGES).sort())}\n`
      : '';
    out = out.replace(line, replacement);
  }

  // A permission that has moved or been renamed must fail the build rather
  // than ship: a Play upload carrying REQUEST_INSTALL_PACKAGES is rejected,
  // and one carrying QUERY_ALL_PACKAGES needs a declaration Covault cannot
  // honestly make.
  if (missing.length) {
    throw new Error(
      'play-manifest: these permissions were not found in the manifest, so they '
      + `were not removed: ${missing.join(', ')}`,
    );
  }
  return out;
}

// Run as a script: read one manifest, write another.
if (process.argv[1] && process.argv[1].endsWith('play-manifest.mjs')) {
  const [, , inPath, outPath] = process.argv;
  if (!inPath || !outPath) {
    console.error('usage: play-manifest.mjs <in AndroidManifest.xml> <out>');
    process.exit(1);
  }
  writeFileSync(outPath, toPlayManifest(readFileSync(inPath, 'utf8')));
  console.error(`play-manifest: wrote the Play manifest to ${outPath}`);
}
